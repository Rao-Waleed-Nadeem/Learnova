"""AI question candidate and content cache models (Phase 9 - AI Integration & Governance)."""

import uuid
from datetime import datetime, timezone
from typing import TYPE_CHECKING, Any, Dict, Optional

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    ForeignKey,
    Integer,
    String,
    Text,
    Uuid,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship
from sqlalchemy.types import JSON

from app.db.base import Base

if TYPE_CHECKING:
    from app.models.course import Course
    from app.models.question import Question
    from app.models.topic import Topic
    from app.models.user import User


class AICandidateQuestion(Base):
    """Quarantined candidate assessment question generated by LLM awaiting teacher review."""

    __tablename__ = "ai_question_candidates"

    __table_args__ = (
        CheckConstraint(
            "type IN ('multiple_choice', 'true_false', 'fill_blank', 'matching', 'short_answer')",
            name="ck_ai_candidates_type",
        ),
        CheckConstraint(
            "difficulty IN ('easy', 'medium', 'hard')",
            name="ck_ai_candidates_difficulty",
        ),
        CheckConstraint(
            "status IN ('pending_review', 'approved', 'rejected')",
            name="ck_ai_candidates_status",
        ),
        CheckConstraint(
            "points > 0",
            name="ck_ai_candidates_points_positive",
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    course_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("courses.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    topic_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("topics.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    author_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    type: Mapped[str] = mapped_column(
        String(32),
        nullable=False,
        index=True,
    )
    difficulty: Mapped[str] = mapped_column(
        String(16),
        nullable=False,
        index=True,
    )
    points: Mapped[int] = mapped_column(
        Integer,
        default=1,
        nullable=False,
    )
    prompt: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )
    explanation: Mapped[Optional[str]] = mapped_column(
        Text,
        nullable=True,
    )
    source_context: Mapped[Optional[str]] = mapped_column(
        Text,
        nullable=True,
    )
    payload: Mapped[Dict[str, Any]] = mapped_column(
        JSON().with_variant(JSONB(), "postgresql"),
        default=dict,
        nullable=False,
    )
    answer_key: Mapped[Dict[str, Any]] = mapped_column(
        JSON().with_variant(JSONB(), "postgresql"),
        default=dict,
        nullable=False,
    )
    status: Mapped[str] = mapped_column(
        String(32),
        default="pending_review",
        nullable=False,
        index=True,
    )
    rejection_reason: Mapped[Optional[str]] = mapped_column(
        Text,
        nullable=True,
    )
    approved_question_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("questions.id", ondelete="SET NULL"),
        nullable=True,
        unique=True,
    )
    provider: Mapped[str] = mapped_column(
        String(64),
        default="gemini",
        nullable=False,
    )
    model: Mapped[str] = mapped_column(
        String(64),
        default="gemini-2.5-flash",
        nullable=False,
    )
    prompt_version: Mapped[str] = mapped_column(
        String(32),
        default="v1",
        nullable=False,
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
        nullable=False,
    )

    # Relationships
    course: Mapped["Course"] = relationship("Course")
    topic: Mapped["Topic"] = relationship("Topic")
    author: Mapped[Optional["User"]] = relationship("User")
    approved_question: Mapped[Optional["Question"]] = relationship("Question")


class AIContentCache(Base):
    """Durable PostgreSQL cache for generated lesson tutoring explanations."""

    __tablename__ = "ai_content_cache"

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )
    cache_key: Mapped[str] = mapped_column(
        String(255),
        unique=True,
        nullable=False,
        index=True,
    )
    content_type: Mapped[str] = mapped_column(
        String(64),
        default="lesson_simplification",
        nullable=False,
    )
    content: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )
    source: Mapped[str] = mapped_column(
        String(64),
        default="gemini",
        nullable=False,
    )
    provider: Mapped[str] = mapped_column(
        String(64),
        default="gemini",
        nullable=False,
    )
    model: Mapped[str] = mapped_column(
        String(64),
        default="gemini-2.5-flash",
        nullable=False,
    )
    prompt_version: Mapped[str] = mapped_column(
        String(32),
        default="v1",
        nullable=False,
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
    )
    expires_at: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        index=True,
    )
